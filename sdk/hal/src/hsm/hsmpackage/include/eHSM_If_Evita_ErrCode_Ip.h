/** @brief convert a eHSM error code into EVITA error code
**
@param [in] ret error code of eHSM, refers to error code in eHSM_Err_Code_Ip.h
**
@return EVITA error code, refers to error code in eHSM_If_Evita_Types_Ip.h
*/
