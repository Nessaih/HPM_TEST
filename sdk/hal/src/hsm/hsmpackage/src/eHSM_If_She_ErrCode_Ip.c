ehsm_int32_t ehsm_she_convert_ret_code(ehsm_int32_t ret)
{
    ehsm_int32_t ret_convert = 0;

    switch (ret)
    {
        case EHSM_ERR_SW_SUCCESS:
        case EHSM_ERR_MAILBOX_SUCCESS:
        case EHSM_ERR_EQUAL_VERSION_COUNTER:
            ret_convert = ERC_NO_ERROR;
            break;
        case EHSM_ERR_EHSM_BUSY:
            ret_convert = ERC_BUSY;
            break;
        case EHSM_ERR_KEY_NOT_AVAILABLE_ERROR:
            ret_convert = ERC_KEY_NOT_AVAILABLE;
            break;
        case EHSM_ERR_KEY_INVALID_ERROR:
            ret_convert = ERC_KEY_INVALID;
            break;
        case EHSM_ERR_KEY_EMPTY_ERROR:
            ret_convert = ERC_KEY_EMPTY;
            break;
        case EHSM_ERR_WRITE_PROTECTED:
            ret_convert = ERC_KEY_WRITE_PROTECTED;
            break;
        case EHSM_ERR_KEY_UPDATE_ERROR:
            ret_convert = ERC_KEY_UPDATE_ERROR;
            break;
        case EHSM_ERR_DEBUG_AUTH_FAILED:
            ret_convert = ERC_NO_DEBUGGING;
            break;
        case EHSM_ERR_MEMORY_FAILURE:
            ret_convert = ERC_MEMORY_FAILURE;
            break;
        case EHSM_ERR_ERC_NO_SECURE_BOOT:
            ret_convert = ERC_NO_SECURE_BOOT;
            break;
        default:
            ret_convert = ERC_GENERAL_ERROR;
            break;
    }
#ifdef CONFIG_HOST_DEBUG_ENABLE
    if (ret_convert != ERC_NO_ERROR)
    {
        SHE_LOG_ERROR("ret = 0x%x\n", ret);
    }
#endif
    return ret_convert;
}
