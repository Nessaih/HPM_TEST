ehsm_uint32_t RNG_Get_Random(ehsm_uint32_t algorithm_identifier, ehsm_uint32_t random_byte_request_size,
ehsm_uint8_t *random_bytes)
{
    ehsm_uint32_t ret = EVITA_GENERAL_ERROR;
    ehsm_cmd_cipher_st rng_param;

    /* random_byte_request_size could be 0, but buffer random_bytes could not be NULL */
    if (NULL == random_bytes)
    {
        ret = EVITA_GENERAL_ERROR;
    }
    else if ((algorithm_identifier != EHSM_SM4_CTRDRBG) && (algorithm_identifier != EHSM_AES_CTRDRBG))
    {
        ret = EVITA_ALGORITHM_ERROR;
    }
    else if (random_byte_request_size > RNG_REQUEST_MAX)
    {
        ret = EVITA_PRNG_REQUEST_OVERSIZE;
    }
    else
    {
        rng_param.cmd_id = EHSM_CMD_RNG_GENERATE;
        rng_param.u_hdr.hdr_rng.algorithm = algorithm_identifier;
        rng_param.output_size = random_byte_request_size;
        rng_param.output_addr = (ehsm_addr_t)random_bytes;
        ret = ehsm_process_sync_service(EHSM_SRV_CRYPTO_RANDOMGENERATE, &rng_param, EHSM_API_TYPE_EVITA);
        ret = ehsm_evita_convert_ret_code(ret);
    }
    return ret;
}
