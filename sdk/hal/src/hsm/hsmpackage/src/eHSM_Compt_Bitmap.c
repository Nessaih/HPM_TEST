bitmap_st *ehsm_bitmap_init(void *bit_ptr, ehsm_uint32_t bit_max)
{
    bitmap_st *bmap = NULL;
    ehsm_uint32_t i, bytes = (bit_max / 8U);

    if ((bit_ptr != NULL) && (bit_max != 0U))
    {
        bmap = (bitmap_st *)bit_ptr;
        bmap->bit_max = bit_max;
        bmap->bit_bytes = bytes;
        for(i = 0U; i < bytes; i++)
        {
            bmap->bit_map[i] = 0x00U;
        }
    }
    return bmap;
}

void ehsm_bitmap_reset(bitmap_st *bmap)
{
    ehsm_uint32_t i = 0U;

    if(NULL != bmap)
    {
        for(; i < bmap->bit_bytes; i++)
        {
            bmap->bit_map[i] = 0x00U;
        }
    }
}

void ehsm_bitmap_set(bitmap_st *bmap, ehsm_uint32_t bit)
{
    ehsm_uint8_t pos = ((bit - 1U) % 8U);
    ehsm_uint32_t bytes = ((bit - 1U) / 8U);

    if((NULL != bmap) && (bit <= bmap->bit_max))
    {
        bmap->bit_map[bytes] |= (0x1U << pos);
    }
}

void ehsm_bitmap_clr(bitmap_st *bmap, ehsm_uint32_t bit)
{
    ehsm_uint8_t pos = ((bit - 1U) % 8U);
    ehsm_uint32_t bytes = ((bit - 1U) / 8U);

    if((NULL != bmap) && (bit <= bmap->bit_max))
    {
        bmap->bit_map[bytes] &= (~(0x1U << pos));
    }
}

ehsm_uint32_t ehsm_bitmap_count(bitmap_st *bmap)
{
    ehsm_uint32_t i = 0U, count = 0U;

    if(NULL != bmap)
    {
        for(; i < bmap->bit_bytes; i++)
        {
            ehsm_uint8_t j = 0U, tmp = bmap->bit_map[i];
            for(; j < 8U; j++)
            {
                if((tmp & 0x1U) != 0U)
                {
                    count++;
                }
                tmp >>= 0x1U;
            }
        }
    }

    return count;
}

ehsm_uint32_t ehsm_bitmap_first(bitmap_st *bmap)
{
    ehsm_uint32_t i = 0U, pos = 0U;
    ehsm_uint32_t result = 0U;

    if(NULL != bmap)
    {
        for(; i < bmap->bit_bytes; i++)
        {
            ehsm_uint8_t j = 0U, tmp = bmap->bit_map[i];
            for(; j < 8U; j++)
            {
                if(0x00U == (tmp & 0x1U))
                {
                    pos = ((i * 8U) + j + 1U);
                    break;
                }
                tmp >>= 0x1U;
            }
            if(0U != pos)
            {
                break;
            }
        }
        if(pos >= bmap->bit_max)
        {
            result = 0U;
        }
        else
        {
            result = pos;
        }
    }

    return result;
}

ehsm_uint32_t ehsm_bitmap_last(bitmap_st *bmap)
{
    ehsm_uint32_t i = 0U, pos = 0U;
    ehsm_uint32_t result = 0U;

    if(NULL != bmap)
    {
        for(i = bmap->bit_bytes; i > 0U; i--)
        {
            ehsm_uint8_t j = 8U, tmp = bmap->bit_map[i - 1U];
            for(; j > 0U; j--)
            {
                if((((i - 1U) * 8U) + j) > bmap->bit_max)
                {
                    tmp <<= 0x1U;
                    continue;
                }
                if(0x00U == (tmp & 0x80U))
                {
                    pos = (((i - 1U) * 8U) + j);
                    break;
                }
                tmp <<= 0x1U;
            }
            if(0U != pos)
            {
                break;
            }
        }
        result = pos;
    }

    return result;
}
